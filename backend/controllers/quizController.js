const Quiz = require('../models/Quiz');
const Topic = require('../models/Topic');
const Subject = require('../models/Subject');
const { generateJSON } = require('../utils/gemini');
const { buildQuizPrompt } = require('../utils/helpers');

// @desc    Generate a new AI Quiz
// @route   POST /api/quiz/generate
// @access  Private
const generateQuiz = async (req, res) => {
  try {
    const { subjectId, topicId, difficulty, numQuestions } = req.body;

    if (!subjectId || !topicId) {
      return res.status(400).json({ success: false, message: 'Subject and Topic are required.' });
    }

    const [subject, topic] = await Promise.all([
      Subject.findById(subjectId),
      Topic.findById(topicId),
    ]);

    if (!subject || !topic) {
      return res.status(404).json({ success: false, message: 'Subject or Topic not found.' });
    }

    const count = parseInt(numQuestions, 10) || 5;
    const userDifficulty = difficulty || req.user.learningLevel || 'intermediate';

    const prompt = buildQuizPrompt({
      topic: topic.name,
      subject: subject.name,
      difficulty: userDifficulty,
      numQuestions: count,
    });

    const parsedData = await generateJSON(prompt);

    if (!parsedData || !Array.isArray(parsedData.questions) || parsedData.questions.length === 0) {
      return res.status(500).json({ success: false, message: 'Failed to generate valid quiz questions. Please retry.' });
    }

    // Format questions
    const validatedQuestions = parsedData.questions.map((q) => ({
      question: q.question,
      options: q.options && q.options.length === 4 ? q.options : ['Option A', 'Option B', 'Option C', 'Option D'],
      correctAnswer: typeof q.correctAnswer === 'number' ? q.correctAnswer : 0,
      explanation: q.explanation || 'Refer to topic fundamentals.',
    }));

    const quiz = await Quiz.create({
      student: req.user.id,
      subject: subjectId,
      topic: topicId,
      difficulty: userDifficulty,
      numQuestions: validatedQuestions.length,
      questions: validatedQuestions,
    });

    res.status(201).json({
      success: true,
      message: 'Quiz generated successfully',
      data: quiz,
    });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

// @desc    Get all quizzes generated by student
// @route   GET /api/quiz
// @access  Private
const getStudentQuizzes = async (req, res) => {
  try {
    const quizzes = await Quiz.find({ student: req.user.id })
      .populate('subject', 'name icon color')
      .populate('topic', 'name difficulty')
      .sort({ generatedAt: -1 });

    res.json({ success: true, count: quizzes.length, data: quizzes });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

// @desc    Get single quiz by ID (without exposing correct answers for in-progress tests if needed)
// @route   GET /api/quiz/:id
// @access  Private
const getQuizById = async (req, res) => {
  try {
    const quiz = await Quiz.findById(req.params.id)
      .populate('subject')
      .populate('topic');

    if (!quiz) {
      return res.status(404).json({ success: false, message: 'Quiz not found' });
    }

    res.json({ success: true, data: quiz });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

module.exports = {
  generateQuiz,
  getStudentQuizzes,
  getQuizById,
};
